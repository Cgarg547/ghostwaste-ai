"""Reproducible synthetic evaluation; does not represent observed restaurant outcomes."""
from pathlib import Path
import sys
ROOT=Path(__file__).resolve().parents[1]
if str(ROOT) not in sys.path: sys.path.insert(0,str(ROOT))
from apps.api.engines import Batch, metrics, moving_average, monte_carlo_risk, seasonal_naive, optimize_purchase

sales=[18,20,19,22,24,23,21,20,22,21,25,26,24,23]
actual=sales[-7:]; train=sales[:-7]
ma=metrics(actual,moving_average(train,7)); sn=metrics(actual,seasonal_naive(train,7))
risk=monte_carlo_risk([Batch("a","greens",12,2,4),Batch("b","greens",8,5,4)],{"greens":3},horizon_days=7,trials=500,seed=42)
baseline={"order_kg":10,"shortage_kg":0,"surplus_kg":2,"cost":10}
optimized=optimize_purchase(available_kg=2,demand_kg=10,unit_cost=1,min_order_kg=0)
text=f"""# Reproducible synthetic evaluation

Generated by `python scripts/run_experiments.py`. Inputs are deliberately synthetic fixture data, not pilot outcomes.

## Forecast benchmark

| Model | MAE | RMSE | WAPE % | Bias |
|---|---:|---:|---:|---:|
| Moving average | {ma['mae']} | {ma['rmse']} | {ma['wape']} | {ma['bias']} |
| Seasonal naive | {sn['mae']} | {sn['rmse']} | {sn['wape']} | {sn['bias']} |

## Risk simulation

500 seeded (42) scenarios: expected expiry-window waste `{risk.expected_waste_kg} kg`; 10–90% interval `{risk.p10_kg}–{risk.p90_kg} kg`; stockout probability `{risk.stockout_probability}`. These estimates are modeled, not observed.

## Purchase comparison

Identical synthetic demand: hand baseline `{baseline}`; constrained linear recommendation `{optimized}`. The solver recommendation is a planning suggestion only and creates no order.

Limitations: this is a fixture-level reproducibility check, not a valid restaurant forecast benchmark or impact claim. LightGBM and real-dataset evaluation remain incomplete.
"""
Path("docs/evaluation-results.md").write_text(text)
print(text)
